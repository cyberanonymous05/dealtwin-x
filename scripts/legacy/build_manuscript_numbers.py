"""Emit the LaTeX \\newcommand macro block for paper_lncs/dealtwinx.tex from the pipeline's result
JSONs, so every number in the manuscript has exactly one machine-generated source. Run after
re-running the studies; paste the printed block over the RESULTS MACROS section of the .tex.
"""

import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

P = os.path.join("data", "processed")


def load(name):
    with open(os.path.join(P, name)) as f:
        return json.load(f)


def main():
    universe = load("deal_universe.json")
    pipeline = load("pipeline_results.json")
    learned = load("learned_metric_results.json")
    outcome = load("outcome_grounded_results.json")
    sig = load("significance_results.json")

    n_deals = len(universe)
    n_industries = len({d["sic"][:2] for d in universe})

    surr = pipeline["valuation_surrogate"]
    comp = surr.get("model_comparison", {})
    xgb = comp.get("xgboost", {"cv_mean_mae_ev_to_revenue": surr["cv_mean_mae_ev_to_revenue"],
                               "cv_mean_r2_log_space": surr["cv_mean_r2_log_space"]})
    ridge = comp.get("ridge", surr.get("model_comparison_ridge_baseline", {}))

    og_base = outcome["naive_industry_size_baseline"]
    og_dna = outcome["full_dealdna_learned_weights_no_multiples"]
    lw_out = og_dna["avg_learned_weights"]
    lw_heur = learned["avg_learned_weights"]

    m = {
        "Ndeals": n_deals,
        "Nindustries": n_industries,
        "Nembdim": pipeline.get("embedding_dim", 833),
        "Nsurrogate": surr["n_training_deals"],
        "Noutcome": outcome["n_deals_with_scorable_multiple"],
        "xgbRtwo": round(xgb["cv_mean_r2_log_space"], 2),
        "xgbMAE": round(xgb["cv_mean_mae_ev_to_revenue"], 2),
        "ridgeRtwo": round(ridge["cv_mean_r2_log_space"], 2),
        "ridgeMAE": round(ridge["cv_mean_mae_ev_to_revenue"], 2),
        "ogMapBase": round(og_base["map"], 3),
        "ogMapDNA": round(og_dna["map"], 3),
        "ogRecBase": round(og_base["recall@10"], 3),
        "ogRecDNA": round(og_dna["recall@10"], 3),
        "ogNdcgBase": round(og_base["ndcg@5"], 3),
        "ogNdcgDNA": round(og_dna["ndcg@5"], 3),
        "sigMeanDiff": round(sig["mean_diff"], 3),
        "sigCIlo": round(sig["bootstrap_ci_95_diff"][0], 3),
        "sigCIhi": round(sig["bootstrap_ci_95_diff"][1], 3),
        "sigP": round(sig["wilcoxon_p_value"], 2),
        "legalWtHeur": round(lw_heur["legal"], 3),
        "legalWtOutcome": round(lw_out["legal"], 3),
        "industryWtHeur": round(lw_heur["industry"], 2),
        "industryWtOutcome": round(lw_out["industry"], 2),
    }

    print("% ---- regenerated by scripts/build_manuscript_numbers.py ----")
    for k, v in m.items():
        print(f"\\renewcommand{{\\{k}}}{{{v}}}")
    print("% -----------------------------------------------------------")


if __name__ == "__main__":
    main()
